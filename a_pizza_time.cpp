#include <bits/stdc++.h>
using namespace std; 

void solve(){
        int n;
        cin>>n;
        int res = 0;
        while(n>2){
                int m = n%3;
                res += n/3;
                n = (n/3) + m;
        }
        cout<<res<<'\n';
}

int main(){
        ios::sync_with_stdio(false);
        cin.tie(nullptr);

        int tt;
        cin >> tt;
        while(tt--){
                solve();
        }
}

